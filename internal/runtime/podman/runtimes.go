package podman

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

// RunscRuntime is the name of the gVisor tier.
const RunscRuntime = "runsc"

// RunscWrapperFile is the generated script Podman runs as "runsc".
const RunscWrapperFile = "runsc"

// PrepareRuntimes resolves the enabled runtimes to what goes into a
// Podman runtime table: for each name the absolute path of the binary
// Podman is to run.
//
// A runtime without a path is looked up in PATH. For runsc the table does
// not get the gVisor binary itself but a wrapper script, written into
// dir, that runs shim (the argv prefix of the runsc shim, normally
// {<sbxd>, "runsc-shim"}) in front of it with runscFlags; see package
// runscshim for why. dir must exist and must allow execution (a tmpfs
// mounted noexec will not do).
func PrepareRuntimes(dir string, enabled []OCIRuntime, shim, runscFlags []string) ([]OCIRuntime, error) {
	out := make([]OCIRuntime, 0, len(enabled))
	for _, r := range enabled {
		path := r.Path
		if path == "" {
			p, err := exec.LookPath(r.Name)
			if err != nil {
				return nil, fmt.Errorf("runtime %s: not found in PATH; install it or give its path (%s=/path/to/%s)", r.Name, r.Name, r.Name)
			}
			if path, err = filepath.Abs(p); err != nil {
				return nil, err
			}
		}
		if fi, err := os.Stat(path); err != nil {
			return nil, fmt.Errorf("runtime %s: %w", r.Name, err)
		} else if !fi.Mode().IsRegular() || fi.Mode().Perm()&0o111 == 0 {
			return nil, fmt.Errorf("runtime %s: %s is not an executable file", r.Name, path)
		}
		if r.Name == RunscRuntime {
			w, err := WriteRunscWrapper(dir, shim, path, runscFlags)
			if err != nil {
				return nil, err
			}
			path = w
		}
		out = append(out, OCIRuntime{Name: r.Name, Path: path})
	}
	return out, nil
}

// WriteRunscWrapper writes the script Podman runs as the OCI runtime
// "runsc" into dir and returns its path. The script only adds fixed
// arguments; all logic is in the shim.
func WriteRunscWrapper(dir string, shim []string, runscPath string, flags []string) (string, error) {
	if len(shim) == 0 || !filepath.IsAbs(shim[0]) {
		return "", fmt.Errorf("runsc wrapper: the shim command %q must start with an absolute path", shim)
	}
	if !filepath.IsAbs(runscPath) {
		return "", fmt.Errorf("runsc wrapper: runsc path %q must be absolute", runscPath)
	}
	var b strings.Builder
	b.WriteString("#!/bin/sh\n# Generated by sbxd; rewritten on every start. See internal/runtime/podman/runscshim.\nexec")
	for _, a := range shim {
		b.WriteString(" " + shellQuote(a))
	}
	b.WriteString(" --runsc " + shellQuote(runscPath))
	for _, f := range flags {
		if !strings.HasPrefix(f, "-") {
			return "", fmt.Errorf("runsc wrapper: %q is not a flag (runsc flags look like --name=value)", f)
		}
		b.WriteString(" " + shellQuote("--flag="+f))
	}
	b.WriteString(" -- \"$@\"\n")
	path := filepath.Join(dir, RunscWrapperFile)
	if err := writeFileAtomic(path, []byte(b.String()), 0o700); err != nil {
		return "", fmt.Errorf("runsc wrapper: %w", err)
	}
	// The directory must allow execution, or every create would fail with
	// a bare "permission denied" from conmon.
	if out, err := exec.Command(path, "--version").CombinedOutput(); err != nil {
		return "", fmt.Errorf("runsc wrapper: %s --version failed: %v: %s (is %s mounted noexec, or is %s not a runsc binary?)",
			path, err, strings.TrimSpace(string(out)), dir, runscPath)
	}
	return path, nil
}

// shellQuote quotes s for /bin/sh.
func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}
